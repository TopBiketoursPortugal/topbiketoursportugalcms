#!/usr/bin/env node
/**
 * Write data/lastmod.json — the last-modified date of every routable content
 * file, read from full git history.
 *
 * The sitemap's `lastmod` normally comes straight from `git log` at build time
 * (lib/lastmod.mjs). The CloudCannon build server has no `.git` folder, so
 * there it comes from this committed file instead; a shallow clone uses it
 * too, because its `git log` would date every page to the clone boundary.
 *
 * The pre-commit hook regenerates it whenever content changes, like
 * data/url-history.json. Files changed in the commit being made are dated now.
 *
 *   pnpm seo:lastmod            regenerate the file
 */

import { writeFileSync } from 'node:fs';
import { relative } from 'node:path';
import { REPO_ROOT } from './lib/routes.mjs';
import { SNAPSHOT, gitHistory, currentFileDates } from './lib/lastmod.mjs';

const history = gitHistory();
if (history !== 'full') {
  console.error(
    `✗ lastmod: git history is ${history ?? 'unavailable'} — cannot derive ` +
      'last-modified dates. Fetch full history (git fetch --unshallow) before regenerating.'
  );
  process.exit(1);
}

const files = Object.fromEntries(currentFileDates());
const payload = {
  $comment:
    'Generated by `pnpm seo:lastmod` — do not edit. Last-modified date per ' +
    'content file, used for the sitemap `lastmod` when the build has no git ' +
    'history (CloudCannon) or only a shallow clone.',
  generated: new Date().toISOString(),
  files
};

writeFileSync(SNAPSHOT, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
console.log(
  `✓ ${relative(REPO_ROOT, SNAPSHOT)} written — ${Object.keys(files).length} files dated`
);
